#!/usr/bin/env node
/**
 * Bundles src/ into one self-contained ES module, dist/signatura-backup.mjs,
 * so the tool can be shipped as a single file. No bundler dependency: the
 * modules only use `import { x } from './y.js'` between themselves, so
 * concatenating them in dependency order and dropping the import/export
 * keywords is enough. Top-level names must be unique across modules, which
 * the script checks.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');
const entry = path.join(srcDir, 'cli.js');

const IMPORT = /^import\s+([\s\S]*?)\s+from\s+'([^']+)';\s*$/gm;
const TOP_LEVEL_NAME = /^(?:export\s+)?(?:async\s+function|function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;

export function build({ outFile = path.join(root, 'dist', 'signatura-backup.mjs') } = {}) {
  const order = [];
  const seen = new Set();
  const builtins = new Map(); // specifier -> Set of import clauses

  function visit(file) {
    if (seen.has(file)) return;
    seen.add(file);
    const source = fs.readFileSync(file, 'utf8');
    for (const [, clause, specifier] of source.matchAll(IMPORT)) {
      if (specifier.startsWith('./')) {
        visit(path.resolve(path.dirname(file), specifier));
      } else if (specifier.startsWith('node:')) {
        if (!builtins.has(specifier)) builtins.set(specifier, new Set());
        builtins.get(specifier).add(clause.replace(/\s+/g, ' '));
      } else {
        throw new Error(`${path.relative(root, file)}: unexpected import of '${specifier}'`);
      }
    }
    order.push({ file, source });
  }
  visit(entry);

  const names = new Map();
  for (const { file, source } of order) {
    for (const [, name] of source.matchAll(TOP_LEVEL_NAME)) {
      if (names.has(name)) {
        throw new Error(`Top-level name '${name}' is defined in both ${names.get(name)} and ${path.relative(root, file)}`);
      }
      names.set(name, path.relative(root, file));
    }
  }

  const parts = [];
  parts.push('#!/usr/bin/env node');
  parts.push('// Generated by scripts/build.js. Edit src/ and rebuild; do not edit this file.');
  parts.push(fs.readFileSync(path.join(root, 'bin', 'signatura-backup.js'), 'utf8')
    .split('\n')
    .filter((line) => !line.startsWith('#!') && !line.includes("await import('../src/cli.js')") && !line.includes('process.exitCode = await main'))
    .join('\n')
    .trim());
  parts.push('');
  for (const [specifier, clauses] of [...builtins].sort()) {
    for (const clause of clauses) {
      // Static imports are hoisted above the warning filter in the prelude,
      // so the one module that warns is loaded dynamically after it.
      parts.push(
        specifier === 'node:sqlite'
          ? `const ${clause} = await import('${specifier}');`
          : `import ${clause} from '${specifier}';`,
      );
    }
  }
  for (const { file, source } of order) {
    parts.push('');
    parts.push(`// ---- ${path.relative(root, file)} ----`);
    parts.push(
      source
        .replace(IMPORT, '')
        .replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\s)/gm, '')
        .trim(),
    );
  }
  parts.push('');
  parts.push('process.exitCode = await main(process.argv.slice(2));');

  const output = `${parts.join('\n')}\n`;
  if (/^\s*export\s/m.test(output) || /^\s*import\s[\s\S]*?from\s+'\.\//m.test(output)) {
    throw new Error('A module uses an import or export form the bundler does not handle.');
  }

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, output, { mode: 0o755 });
  return outFile;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outFile = build();
  const size = fs.statSync(outFile).size;
  console.log(`${path.relative(process.cwd(), outFile)} (${(size / 1024).toFixed(0)} KB)`);
}
